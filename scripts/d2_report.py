#!/usr/bin/env python3
"""Build the combined D2 evidence report (Markdown) from results/d2/<set>/.

Usage: python3 scripts/d2_report.py results/d2 > results/d2/SUMMARY.md
"""
import pathlib
import re
import statistics
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from summarize_results import VIOLATIONS, load_set, table  # noqa: E402

SETS = [
    ("default", "Default parameters (work_shift 0, traffic_speed 3, noise 0.02)"),
    ("var_shift_m2", "Geometry variation: work_shift = -2.0 m"),
    ("var_shift_p2", "Geometry variation: work_shift = +2.0 m"),
    ("var_traffic_2", "Traffic variation: traffic_speed = 2.0 m/s (S3)"),
    ("var_traffic_4", "Traffic variation: traffic_speed = 4.0 m/s (S3)"),
    ("var_noise_005", "Noise variation: noise = 0.05 m (upper bound)"),
    ("ablation_no_gap", "Ablation: radar traffic-gap check disabled (use_traffic_gap:=false), S3"),
    ("ablation_no_obstacle", "Ablation: LiDAR corridor check disabled (use_obstacle_check:=false), S5"),
]


def stats(vals, f="{:.2f}"):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "-"
    if len(vals) == 1:
        return f.format(vals[0])
    return f"{f.format(statistics.mean(vals))} ± {f.format(statistics.pstdev(vals))}"


def ok(r):
    return r["result"] is not None and r["result"].get("pass")


def scen(r):
    return int(r["result"]["scenario"]) if r["result"] else 0


def aggregate(name, desc, runs):
    res = [r["result"] for r in runs if r["result"]]
    viol = {k: sum(1 for x in res if x.get(k)) for k in VIOLATIONS}
    vtxt = ", ".join(f"{k} ×{n}" for k, n in viol.items() if n) or "none"
    mc = min((x["min_clearance"] for x in res), default=None)
    vmax = max((x["max_speed"] for x in res), default=None)
    return (f"| `{name}` | {desc} | {len(runs)} | {sum(1 for r in runs if ok(r))}/{len(runs)} | {vtxt} | "
            f"{'-' if mc is None else f'{mc:.3f}'} | {'-' if vmax is None else f'{vmax:.2f}'} |")


def per_scenario(runs):
    lines = ["| scenario | runs | pass | sim time [s] | stopped [s] | min clearance [m] | mean \\|cte\\| [m] | "
             "max \\|cte\\| [m] | key measurement |",
             "|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    for s in range(1, 6):
        rs = [r for r in runs if scen(r) == s]
        if not rs:
            continue
        m = [r["metrics"] for r in rs]
        key = "-"
        if s == 2:
            key = f"GO confirm after event {stats([x.get('go_latency') for x in m])} s"
        elif s == 3:
            key = (f"yield {stats([x.get('yield_seconds') for x in m], '{:.1f}')} s; clearance to car "
                   f"{stats([x.get('traffic_clearance_min') for x in m])} m")
        elif s == 4:
            key = f"resume after recovery {stats([x.get('resume_latency') for x in m])} s"
        elif s == 5:
            key = (f"detection {stats([x.get('detect_latency') for x in m], '{:.3f}')} s; clearance to obstacle "
                   f"{stats([x.get('obstacle_clearance_min') for x in m])} m")
        elif s == 1:
            key = f"unexplained stops {sum(x.get('unexplained_stops', 0) for x in m)}"
        lines.append(
            f"| S{s} | {len(rs)} | {sum(1 for r in rs if ok(r))} | {stats([r['result']['time'] for r in rs])} | "
            f"{stats([r['result']['stopped_seconds'] for r in rs])} | "
            f"{stats([r['result']['min_clearance'] for r in rs], '{:.3f}')} | "
            f"{stats([x.get('tracking', {}).get('mean_abs_cte') for x in m], '{:.3f}')} | "
            f"{stats([x.get('tracking', {}).get('max_abs_cte') for x in m], '{:.3f}')} | {key} |")
    return "\n".join(lines)


def ablation(final, abl, s, label):
    f = [r for r in final if scen(r) == s]
    a = [r for r in abl if scen(r) == s]
    if not f or not a:
        return ""
    rows = []
    for name, rs in (("final method", f), (label, a)):
        res = [r["result"] for r in rs]
        rows.append(f"| {name} | {len(rs)} | {sum(1 for r in rs if ok(r))}/{len(rs)} | "
                    f"{sum(1 for x in res if x.get('collision'))} | {stats([x['min_clearance'] for x in res], '{:.3f}')} | "
                    f"{stats([x['time'] for x in res])} | {stats([x['stopped_seconds'] for x in res])} |")
    return ("| variant | runs | pass | collisions | min clearance [m] | sim time [s] | stopped [s] |\n"
            "|---|---:|---:|---:|---:|---:|---:|\n" + "\n".join(rows))


def main():
    root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "results/d2")
    sets = {name: load_set(root / name) for name, _ in SETS if (root / name).is_dir()}
    print("# D2 evidence summary\n")
    print("Generated by `scripts/d2_report.py` from the episode folders written by `scripts/run_d2.sh`. "
          "Every episode is a fresh headless launch (`rviz:=false visualize:=false`); per-run logs, "
          "evaluator JSON, run metadata and bag-derived measurements are in `results/d2/<set>/s<S>_seed<N>/`. "
          "Bags are not committed (regenerate them with the same script).\n")
    env = root / "default" / "environment.txt"
    if env.exists():
        print("```\n" + env.read_text().strip() + "\n```\n")

    print("## Overview\n")
    print("| set | description | runs | pass | violations | min clearance [m] | max speed [m/s] |")
    print("|---|---|---:|---:|---|---:|---:|")
    for name, desc in SETS:
        if name in sets:
            print(aggregate(name, desc, sets[name]))

    if "default" in sets:
        print("\n## Default runs per scenario (mean ± std over seeds)\n")
        print(per_scenario(sets["default"]))
    var = [r for n in ("var_shift_m2", "var_shift_p2", "var_traffic_2", "var_traffic_4", "var_noise_005")
           for r in sets.get(n, [])]
    if var:
        print("\n## All variation runs per scenario (mean ± std)\n")
        print(per_scenario(var))

    print("\n## Ablation comparison\n")
    print("Same seeds and parameters; only the named check is disabled (launch argument). Final-method rows "
          "use the default set.\n")
    final = sets.get("default", [])
    if "ablation_no_gap" in sets:
        print("**S3 without the radar traffic-gap check** (LiDAR corridor check still active):\n")
        print(ablation(final, sets["ablation_no_gap"], 3, "no radar gap check") + "\n")
    if "ablation_no_obstacle" in sets:
        print("**S5 without the LiDAR corridor check:**\n")
        print(ablation(final, sets["ablation_no_obstacle"], 5, "no LiDAR corridor check") + "\n")

    nl = root / "node_loss"
    if nl.is_dir():
        import json
        print("## Node loss (stop and recovery)\n")
        print("One pipeline node is killed with SIGKILL while the vehicle is in the bypass (S1 seed 1, t = 12 s, "
              "3.5 m/s) and restarted with the same parameters 5 s later (`scripts/node_loss_test.py`).\n")
        print("| node killed | x at kill [m] | stopped by | time to stop [s] | distance [m] | lateral drift [m] | "
              "commands while down | motion after restart [s] | episode |")
        print("|---|---:|---|---:|---:|---:|---:|---:|---|")
        who = {"sense": "Plan scene deadline -> SAFE_STOP hold plans -> Act speed 0",
               "plan": "Act plan expiry -> speed 0, steering held",
               "act": "simulator command watchdog (no commands)"}
        for n in ("sense", "plan", "act"):
            f = nl / n / "node_loss.json"
            if not f.exists():
                continue
            d = json.loads(f.read_text())
            st, ev, rs = d.get("stop") or {}, d.get("evaluator") or {}, d.get("restart") or {}
            ca = d.get("commands_after_kill") or {}
            ep = ("PASS" if ev.get("pass") else "FAIL") + f" ({ev.get('time', '-')} s)"
            print(f"| {n} | {d['kill']['x']:.2f} | {who[n]} | {st.get('time_to_stop', '-')} | {st.get('distance', '-')} | "
                  f"{st.get('lateral_drift', '-')} | {ca.get('count', '-')} | "
                  f"{rs.get('first_motion_after_restart', '-')} | {ep} |")
        print()

    off = root / "offline"
    if off.is_dir():
        print("## Offline (ROS-free) evidence\n")
        suite = off / "closed_loop_suite.txt"
        if suite.exists():
            print(f"- Closed-loop regression suite: `{suite.read_text().strip().splitlines()[-1]}` "
                  "(S1-S5 × seeds 1-3 × work_shift {0, ±2} × noise {0.02, 0, 0.05} × extra command delay "
                  "{0, 0.1 s}; S3 also × traffic_speed {2, 3, 4}).")
        for t in ("test_perception.txt", "test_planning.txt"):
            p = off / t
            if p.exists():
                print(f"- `{t[:-4]}`: `{p.read_text().strip().splitlines()[-1]}`")
        perc = off / "test_perception.txt"
        if perc.exists():
            txt = perc.read_text()
            m = re.search(r"panel confusion matrix.*?\n((?:  .*\n){3})", txt)
            if m:
                print("\nHeld-out panel recognition (independently generated images, own RNG/seed, noise up to "
                      "1.5× the contract, ±2 px disc offset); rows = truth, columns = prediction:\n")
                print("| truth \\ predicted | UNKNOWN | STOP | GO |\n|---|---:|---:|---:|")
                for line in m.group(1).strip("\n").splitlines():
                    parts = line.split()
                    print(f"| {parts[0]} | {' | '.join(parts[1:])} |")
        abl = off / "ablations.txt"
        if abl.exists():
            lines = [ln for ln in abl.read_text().splitlines() if ln.startswith("S")]
            def count(pred):
                sel = [ln for ln in lines if pred(ln)]
                return f"{sum(1 for ln in sel if 'pass=1' in ln)}/{len(sel)} pass"
            print(f"\n- Offline ablations (`offline/ablations.txt`): S3 final {count(lambda l: l.startswith('S3') and 'no-gap' not in l)}, "
                  f"S3 no-gap {count(lambda l: l.startswith('S3') and 'no-gap' in l)}; "
                  f"S5 final {count(lambda l: l.startswith('S5') and 'no-obstacle' not in l)}, "
                  f"S5 no-obstacle {count(lambda l: l.startswith('S5') and 'no-obstacle' in l)}.")

    print("\n## Per-run tables\n")
    for name, desc in SETS:
        if name in sets:
            print(f"### `{name}`: {desc}\n")
            print(table(sets[name]) + "\n")
    print("Column notes: *min clearance* is the evaluator's disc-to-disc minimum over all objects; *rejected cmds* "
          "includes startup ticks before the first valid command; *entry t* is when the vehicle front crossed "
          "x = 25 m; *|cte|* is the tracking error to the solution's own planned path while moving; scenario "
          "measurements are defined in `scripts/analyze_bag.py`.")


if __name__ == "__main__":
    main()
